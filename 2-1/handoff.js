/* 통합과학2 Ⅱ-1 생태계와 환경 변화 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "생태계 = <b>생물적 요인</b>(생산자·소비자·분해자) + <b>비생물적 요인</b>(빛·온도·물·토양·공기).",
  "생산자는 광합성으로 양분을 스스로 만들고, 소비자는 다른 생물을 먹어 양분을 얻는다. 생산자를 먹으면 <b>1차 소비자</b>, 1차 소비자를 먹으면 <b>2차 소비자</b>.",
  "<b>작용</b>(환경 → 생물), <b>반작용</b>(생물 → 환경), <b>상호 작용</b>(생물 ↔ 생물): 영향을 주는 쪽과 받는 쪽을 가리면 방향이 보인다."
];
var D02 = [
  "에너지는 영양 단계를 올라갈 때마다 <b>일부(약 10%)만</b> 전달된다. 그래서 위 단계일수록 생물의 양이 적은 <b>생태 피라미드</b>가 된다.",
  "<b>생태계 평형</b>: 한 종의 수가 바뀌어도 먹이 관계를 따라 영향이 퍼지다가 다시 균형을 찾는다. 늑대가 돌아오자 엘크가 줄고 숲이 되살아났다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「생태계 평형」에서 풀·버드나무(생산자) → 엘크(1차 소비자) → 늑대(2차 소비자)로 이어지는 먹이 관계와 상호 작용이 다시 쓰입니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[1], "이 이야기에서는 이 단계를 따라 <b>에너지가 얼마나 전달되는지</b>, 늑대 한 종이 사라지면 엘크와 숲이 어떻게 되는지 셈해 봅니다."],
  check: { q: "엘크를 잡아먹는 늑대는 어느 단계일까요?", options: ["생산자", "1차 소비자", "2차 소비자", "분해자"], a: 2, why: "풀(생산자)을 먹는 엘크가 1차 소비자, 엘크를 먹는 늑대는 2차 소비자입니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「지구 환경 변화」에서는 이런 평형을 한꺼번에 흔들 수 있는 더 큰 환경 변화, 기후 변화를 다룹니다."
});

/* 03 — 시작 전 */
window.sthBridge({
  ep: "ep3", always: true, title: "시작 전 1분 · 이 이야기에 필요한 것은 두 가지뿐",
  lines: [
    "모든 물체는 온도에 따라 <b>복사 에너지</b>를 내놓는다. 태양은 주로 <b>가시광선</b>, 지구는 주로 <b>적외선</b>(지구 복사)을 내놓는다.",
    "들어오는 에너지와 나가는 에너지가 같아지는 온도에서 지구의 평균 기온이 일정하게 유지된다."
  ],
  note: "01·02를 하지 않았어도 바로 시작할 수 있습니다."
});
})();
