  check: { q: "석탄의 에너지 100을 넣은 발전소의 효율이 40%라면, 전기가 되지 못한 60은 어떻게 될까?", options: ["사라진다", "대부분 열로 흩어진다", "발전소 안에 쌓인다"], a: 1, why: "에너지는 사라지지 않습니다. 전기로 바뀌지 못한 60은 대부분 굴뚝과 냉각수의 열로 흩어집니다." }
