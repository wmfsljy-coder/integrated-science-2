  note: "02 「기술 발전과 빅데이터」에서는 오늘날 감염병 추적·예측에 쓰이는 <b>빅데이터</b>를 다루고, 데이터를 모으는 길목이 치우치면(편향) 무엇이 틀어지는지 따집니다."
