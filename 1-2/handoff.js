/* 통합과학2 Ⅰ-2 화학 변화 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "물질이 <b>산소를 얻으면 산화, 잃으면 환원</b>이다. 한 물질이 산소를 잃으면 다른 물질이 그 산소를 얻으므로 둘은 <b>언제나 함께</b> 일어난다.",
  "산소가 없어도 <b>전자를 잃으면 산화, 얻으면 환원</b>이다. 금속의 반응성은 <b>Mg &gt; Zn &gt; Fe &gt; Cu &gt; Ag</b>.",
  "철이 공기 중 산소와 결합하는 것(녹, 손난로)도 <b>산화</b>이다."
];
var D02 = [
  "산은 물에 녹아 <b>H⁺</b>을, 염기는 <b>OH⁻</b>을 내놓는다. 기준은 화학식이 아니라 물에 녹아 내놓는 이온이다.",
  "<b>H⁺ + OH⁻ → H₂O</b>: 1 : 1로 만나 물이 되고 <b>열이 나온다</b>(중화열). 반응한 수가 가장 많은 <b>중화점</b>에서 온도가 가장 높다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「산과 염기」에서는 마그네슘이 산에 녹아 수소가 나오는 까닭(H⁺이 전자를 얻음)으로, 03 「반응과 에너지 출입」에서는 철 가루 손난로의 열로 다시 쓰입니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[1], "이 이야기의 검사대에서 마그네슘 조각을 산에 넣으면 수소 기체가 나옵니다. 산의 <b>H⁺이 마그네슘에게서 전자를 얻어</b> 수소가 되기 때문입니다."],
  check: { q: "마그네슘(Mg)이 전자를 잃고 Mg²⁺이 되었습니다. 마그네슘에 일어난 변화는?", options: ["산화", "환원", "중화"], a: 0, why: "전자를 잃으면 산화입니다. 그 전자를 얻은 H⁺은 환원되어 수소 기체가 됩니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「반응과 에너지 출입」에서 중화 반응은 <b>발열 반응</b>의 한 예로 다시 나옵니다."
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: [D01[2], "이 이야기의 손난로는 바로 이 <b>철의 산화</b>에서 나오는 열을 씁니다. 철 가루가 다 산화되면 더는 열이 나오지 않습니다."],
  check: { q: "손난로 속 철 가루가 따뜻해지는 까닭은?", options: ["철이 산소와 결합하는 산화 반응이 열을 내놓으므로", "철이 산소를 잃는 환원 반응이 열을 내놓으므로", "철이 물에 녹아 H⁺을 내놓으므로"], a: 0, why: "철이 공기 중 산소와 결합해 산화 철이 되며 열을 방출합니다." }
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[1], "이 이야기의 마지막 분류에서 ‘산과 염기를 섞으면 용액의 온도가 올라간다’를 발열·흡열 가운데 어디에 넣을지 판단할 때 씁니다."],
  check: { q: "묽은 염산에 수산화 나트륨 수용액을 넣어 가며 온도를 재면, 온도가 가장 높은 때는?", options: ["넣기 전", "중화점", "염기를 가장 많이 넣었을 때"], a: 1, why: "중화점에서 반응한 H⁺과 OH⁻의 수가 가장 많아 중화열도 가장 많이 나옵니다." }
});
})();
